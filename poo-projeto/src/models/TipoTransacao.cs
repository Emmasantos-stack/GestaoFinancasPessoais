namespace SistemaFinanceiro
{

    // Enumeração que representa o tipo de uma transação financeira. Esta enumeração é utilizada para distinguir se uma transação corresponde a uma receita ou a uma despesa.
    public enum TipoTransacao
    {
    // Representa uma entrada de dinheiro (receita).

        Receita = 1,
    // Representa uma saída de dinheiro (despesa).
        Despesa = 2
    }
}